#!/usr/bin/env node
/**
 * Sync BYOK model suggestions from models.dev.
 *
 * Rules:
 * - released within the last RECENCY_MONTHS months (models.dev release_date)
 * - tool_call + text output (Peal chat needs tools)
 * - resolvable in the pi-ai registry (the runtime that actually serves them)
 * - OpenRouter: allowlisted vendors, capped per vendor so no single vendor
 *   floods the suggestion list
 * - no alias (~id) or retired-provider entries
 *
 * Run: bun run models:sync   → writes lib/ai/byokModels.generated.ts
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getModel } from '@earendil-works/pi-ai'

const RECENCY_MONTHS = 12
const MODELS_DEV_URL = 'https://models.dev/api.json'

const OPENROUTER_VENDORS = [
  'anthropic',
  'openai',
  'google',
  'deepseek',
  'moonshotai',
  'z-ai',
  'x-ai',
  'qwen',
]
const OPENROUTER_PER_VENDOR = 5
const MAX_PER_PROVIDER = { openai: 24, opencode: 30 }
const PINNED = { openrouter: ['openrouter/auto'] }
const EXCLUDE = /^(~|minimax)/i

const cutoff = new Date()
cutoff.setMonth(cutoff.getMonth() - RECENCY_MONTHS)
const cutoffIso = cutoff.toISOString().slice(0, 10)

function releaseDate(entry) {
  const raw = entry.release_date || ''
  return raw.length === 7 ? `${raw}-01` : raw
}

function eligible(id, entry) {
  if (EXCLUDE.test(id)) return false
  if (releaseDate(entry) < cutoffIso) return false
  if (entry.tool_call !== true) return false
  if (!(entry.modalities?.output ?? []).includes('text')) return false
  return true
}

const api = await fetch(MODELS_DEV_URL).then((r) => {
  if (!r.ok) throw new Error(`models.dev ${r.status}`)
  return r.json()
})

const out = {}
const dropped = []

for (const provider of ['openai', 'openrouter', 'opencode']) {
  const models = api[provider]?.models ?? {}
  // models.dev freshness first, then pi-ai resolution, then cap — otherwise the
  // newest entries (which pi-ai hasn't caught up to) starve every vendor slot.
  const fresh = Object.entries(models)
    .filter(([id, entry]) => eligible(id, entry))
    .filter(([id]) => {
      if (getModel(provider, id)) return true
      dropped.push(`${provider}:${id} (not in pi-ai)`)
      return false
    })
    .sort((a, b) => releaseDate(b[1]).localeCompare(releaseDate(a[1])))

  let kept
  if (provider === 'openrouter') {
    kept = []
    for (const vendor of OPENROUTER_VENDORS) {
      kept.push(
        ...fresh
          .filter(([id]) => id.split('/')[0] === vendor)
          .slice(0, OPENROUTER_PER_VENDOR)
          .map(([id]) => id),
      )
    }
  } else {
    kept = fresh.slice(0, MAX_PER_PROVIDER[provider] ?? fresh.length).map(([id]) => id)
  }

  out[provider] = [...(PINNED[provider] ?? []), ...kept]
}

const today = new Date().toISOString().slice(0, 10)
const body = `// GENERATED by scripts/sync-byok-models.mjs — do not edit by hand.
// Source: models.dev · cutoff: released since ${cutoffIso} (${RECENCY_MONTHS}mo) · synced ${today}
// Run \`bun run models:sync\` to refresh.
export const GENERATED_BYOK_MODELS: Record<string, string[]> = ${JSON.stringify(out, null, 2)}
`

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../lib/ai/byokModels.generated.ts')
writeFileSync(target, body)

for (const [provider, ids] of Object.entries(out)) {
  console.log(`${provider}: ${ids.length} models`)
}
if (dropped.length) console.log(`dropped (no pi-ai entry): ${dropped.join(', ')}`)
console.log(`→ ${target}`)
